export function generateCsvFromRecords(records: ValuationRecord[]): string {
  const headers = [
    'player',
    'year',
    'ln_price_to_purse',
    'sold_price_cr',
    'is_overseas',
    'is_capped',
    'strike_rate',
    'average',
    'boundary_pct',
    'six_pct',
    'economy_rate',
    'bowling_strike_rate',
    'dot_ball_pct',
    'wickets_per_match',
    'matches_played',
    'predicted_ln_price',
    'residual',
    'gap_percentage',
    'dominant_archetype',
    'z_score',
    'is_outlier',
  ];

  const rows = records.map((r) =>
    [
      r.player,
      r.year,
      r.ln_price_to_purse.toFixed(6),
      r.sold_price_cr.toFixed(6),
      r.is_overseas,
      r.is_capped,
      r.strike_rate.toFixed(6),
      r.average.toFixed(6),
      r.boundary_pct.toFixed(6),
      r.six_pct.toFixed(6),
      r.economy_rate.toFixed(2),
      r.bowling_strike_rate.toFixed(2),
      r.dot_ball_pct.toFixed(2),
      r.wickets_per_match.toFixed(2),
      r.matches_played,
      r.predicted_ln_price.toFixed(6),
      r.residual.toFixed(6),
      r.gap_percentage.toFixed(6),
      r.dominant_archetype,
      r.z_score.toFixed(6),
      r.is_outlier,
    ].join(',')
  );

  return [headers.join(','), ...rows].join('\n');
}
